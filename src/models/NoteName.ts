export interface Cell {
  octave: number;
  index: number;
}

export const allNotes = [...new Set([...octaveZeroNoteNames, ...octaveOneNoteNames, ...octaveTwoNoteNames, ...octaveThreeNoteNames, ...octaveFourNoteNames])] as const;

type NoteName = (typeof allNotes)[number];
export default NoteName;
export type TransliteratedNoteNameOctaveOne = (typeof octaveOneNoteNames)[number];
export type TransliteratedNoteNameOctaveZero = (typeof octaveZeroNoteNames)[number];
export type TransliteratedNoteNameOctaveTwo = (typeof octaveTwoNoteNames)[number];
export type TransliteratedNoteNameOctaveThree = (typeof octaveThreeNoteNames)[number];
export type TransliteratedNoteNameOctaveFour = (typeof octaveFourNoteNames)[number];

/**
 * Gets the global index of a note name across all octaves.
 * 
 * @param noteName - The note name to find
 * @returns The index in the combined array of all note names
 */
export function getNoteNameIndex(noteName: NoteName): number {
  return allNotes.indexOf(noteName);
}

/**
 * Gets the octave and index within that octave for a note name.
 * 
 * @param noteName - The note name to analyze
 * @returns Cell object containing octave and index within that octave
 */
export function getNoteNameIndexAndOctave(noteName: NoteName): Cell {
  if (octaveZeroNoteNames.includes(noteName)) return { octave: 0, index: octaveZeroNoteNames.indexOf(noteName) };
  if (octaveOneNoteNames.includes(noteName)) return { octave: 1, index: octaveOneNoteNames.indexOf(noteName) };
  if (octaveTwoNoteNames.includes(noteName)) return { octave: 2, index: octaveTwoNoteNames.indexOf(noteName) };
  if (octaveThreeNoteNames.includes(noteName)) return { octave: 3, index: octaveThreeNoteNames.indexOf(noteName) };
  if (octaveFourNoteNames.includes(noteName)) return { octave: 4, index: octaveFourNoteNames.indexOf(noteName) };
  return { index: -1, octave: -1 };
}

/**
 * Position of the note each nīm and tīk position varies, by index within an
 * octave. In the PAO note naming nīm X is X lowered and tīk X is X raised;
 * every octave array shares one position layout, so the parents are read
 * once from octave one's names. octaveOneNoteNames.length means position 0 of the next octave
 * (nīm nawā → nawā).
 */
const PARENT_POSITION: Map<number, number> = (() => {
  const plain = (name: string) =>
    name.normalize("NFD").replace(/[̀-ͯʿʾ]/g, "").replace(/^(qarar )+/, "");
  const variant = (name: string) => plain(name).match(/^(nim|tik) (.+)$/);
  const parents = new Map<number, number>();
  octaveOneNoteNames.forEach((name, index) => {
    const match = variant(name);
    if (!match) return;
    const target = match[2].split("/")[0].trim();
    // The varied note is plain (tīk ḥiṣār → ḥiṣār) or itself a variant (nīm tīk ḥiṣār → tīk ḥiṣār)
    const parts = (candidate: string) => plain(candidate).split("/").map((part) => part.trim());
    const position = octaveOneNoteNames.findIndex((candidate) =>
      variant(match[2]) ? candidate !== name && parts(candidate)[0] === target : !variant(candidate) && parts(candidate).includes(target)
    );
    if (position !== -1) parents.set(index, position);
    else if (plain(octaveTwoNoteNames[0]) === target) parents.set(index, octaveOneNoteNames.length);
    else throw new Error(`No parent note name found for "${name}"`);
  });
  return parents;
})();

/**
 * The note a nīm or tīk note varies: tīk kawasht → kawasht, nīm zīrgūleh →
 * zīrgūleh, jawāb tīk zīrgūleh → shahnāz, nīm nawā → nawā.
 *
 * @param noteName - The note name to analyze
 * @returns The parent note name, or null for a note that is not a nīm or tīk note
 */
export function getParentNoteName(noteName: NoteName): NoteName | null {
  const { octave, index } = getNoteNameIndexAndOctave(noteName);
  const position = PARENT_POSITION.get(index);
  if (octave === -1 || position === undefined) return null;
  if (position === octaveOneNoteNames.length) {
    const parent = getNoteNameFromIndexAndOctave({ octave: octave + 1, index: 0 });
    return parent === "none" ? null : parent;
  }
  return getNoteNameFromIndexAndOctave({ octave, index: position });
}

/**
 * Gets the note name from octave and index coordinates.
 * 
 * @param cell - Cell object containing octave and index
 * @returns The corresponding note name
 */
export function getNoteNameFromIndexAndOctave(cell: Cell): NoteName {
  const { octave, index } = cell;
  if (octave === 0) return octaveZeroNoteNames[index];
  else if (octave === 1) return octaveOneNoteNames[index];
  else if (octave === 2) return octaveTwoNoteNames[index];
  else if (octave === 3) return octaveThreeNoteNames[index];
  else if (octave === 4) return octaveFourNoteNames[index];
  else return "none";
}

/**
 * Shifts a note name by the specified number of octaves.
 * 
 * @param noteName - The note name to shift
 * @param shift - Number of octaves to shift (positive = up, negative = down)
 * @returns The shifted note name
 */
export function shiftNoteName(noteName: NoteName, shift: number): NoteName {
  const { index, octave } = getNoteNameIndexAndOctave(noteName);

  return getNoteNameFromIndexAndOctave({
    index,
    octave: octave + shift,
  }) as NoteName;
}

/**
 * True when two note names occupy the same modal degree slot — that is, they are
 * the same degree in different registers (qarār rāst / rāst / kurdān).
 *
 * Deliberately octave-blind: a register shift is not taṣwīr, so a jins seated on
 * rāst is still "jins rāst" when it appears on kurdān. Callers that must tell
 * registers apart (see the tier-1 rule in ajnasOrdering.ts) have to compare the
 * exact note names instead.
 */
export function sameModalDegreeSlot(a: string, b: string): boolean {
  const aIdx = getNoteNameIndexAndOctave(a as NoteName).index;
  const bIdx = getNoteNameIndexAndOctave(b as NoteName).index;
  return aIdx >= 0 && bIdx >= 0 && aIdx === bIdx;
}
